#!/usr/bin/env node

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));

export function loadTokenFiles(tokenDirectory = 'design-system/tokens') {
  const directory = resolve(tokenDirectory);
  return {
    schema: readJson(resolve(directory, 'schema.json')),
    dark: readJson(resolve(directory, 'dark.tokens.json')),
    light: readJson(resolve(directory, 'light.tokens.json')),
    print: readJson(resolve(directory, 'print.tokens.json')),
  };
}

function declarations(tokens) {
  return Object.entries(tokens)
    .map(([name, value]) => `  --${name}: ${value};`)
    .join('\n');
}

export function renderTokens(tokenFiles) {
  return `/* Generated by scripts/generate-design-tokens.mjs from design-system/tokens/*.json. Do not edit. */\n`
    + `:root,\n[data-theme="light"] {\n${declarations(tokenFiles.light)}\n}\n\n`
    + `[data-theme="dark"] {\n${declarations(tokenFiles.dark)}\n}\n\n`
    + `@media print {\n  :root {\n${declarations(tokenFiles.print).replaceAll('\n', '\n  ')}\n  }\n}\n`;
}

function assertSchema({ schema, dark, light, print }) {
  const required = [...schema.requiredKeys].sort();
  for (const [theme, tokens] of [['dark', dark], ['light', light]]) {
    const actual = Object.keys(tokens).sort();
    if (JSON.stringify(actual) !== JSON.stringify(required)) {
      throw new Error(`${theme}.tokens.json does not match schema.json`);
    }
  }
  if (Object.keys(print).length !== 9 || Object.keys(print).some((key) => !key.startsWith('print-'))) {
    throw new Error('print.tokens.json must contain exactly nine print-* keys');
  }
}

export function generate({
  tokenDirectory = 'design-system/tokens',
  outputPath = 'src/styles/tokens.css',
  check = false,
} = {}) {
  const tokenFiles = loadTokenFiles(tokenDirectory);
  assertSchema(tokenFiles);
  const expected = renderTokens(tokenFiles);
  const target = resolve(outputPath);

  if (check) {
    const actual = readFileSync(target, 'utf8');
    if (actual !== expected) {
      throw new Error(`${outputPath} is stale; run pnpm tokens:generate`);
    }
    return expected;
  }

  writeFileSync(target, expected, 'utf8');
  return expected;
}

function cliArgument(name, fallback) {
  const index = process.argv.indexOf(name);
  return index === -1 ? fallback : process.argv[index + 1];
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  try {
    const check = process.argv.includes('--check');
    generate({
      tokenDirectory: cliArgument('--tokens', 'design-system/tokens'),
      outputPath: cliArgument('--output', 'src/styles/tokens.css'),
      check,
    });
    console.log(check ? 'DESIGN_TOKEN_GENERATION_IDEMPOTENT' : 'DESIGN_TOKENS_GENERATED');
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
